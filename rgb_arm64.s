//go:build arm64 && !noasm

#include "textflag.h"

#define UMLAL2_4S(m, n, d) WORD $(0x6E608000 | ((m) << 16) | ((n) << 5) | (d))
#define UMLAL4S(m, n, d) WORD $(0x2E608000 | ((m) << 16) | ((n) << 5) | (d))
#define UMLSL2_4S(m, n, d) WORD $(0x6E60A000 | ((m) << 16) | ((n) << 5) | (d))
#define UMLSL4S(m, n, d) WORD $(0x2E60A000 | ((m) << 16) | ((n) << 5) | (d))
#define UMULL2_4S(m, n, d) WORD $(0x6E60C000 | ((m) << 16) | ((n) << 5) | (d))
#define UMULL4S(m, n, d) WORD $(0x2E60C000 | ((m) << 16) | ((n) << 5) | (d))

// NEON packed RGB to YCbCr planes, bit-identical to rgbToYCbCr. Go's arm64
// assembler has no integer multiply; the macros above encode the multiply-long forms.

// func rgbToYCbCrNEON(dstY, dstCb, dstCr, src []byte, n int)
TEXT ·rgbToYCbCrNEON(SB), NOSPLIT, $0-104
	MOVD dstY_base+0(FP), R0
	MOVD dstCb_base+24(FP), R1
	MOVD dstCr_base+48(FP), R2
	MOVD src_base+72(FP), R3
	MOVD n+96(FP), R4

	MOVD $19595, R5
	VDUP R5, V16.H8 // Y R
	MOVD $38470, R5
	VDUP R5, V17.H8 // Y G
	MOVD $7471, R5
	VDUP R5, V18.H8 // Y B
	MOVD $11056, R5
	VDUP R5, V19.H8 // Cb R
	MOVD $21712, R5
	VDUP R5, V20.H8 // Cb G
	MOVD $32768, R5
	VDUP R5, V21.H8 // B and Cr R
	MOVD $27440, R5
	VDUP R5, V22.H8 // Cr G
	MOVD $5328, R5
	VDUP R5, V23.H8 // Cr B
	MOVD $255, R5
	VDUP R5, V24.S4
	MOVD $32768, R5
	VDUP R5, V25.S4
	MOVD $8421376, R5
	VDUP R5, V26.S4

loop:
	CMP $16, R4
	BLT done

	VLD4.P 64(R3), [V0.B16, V1.B16, V2.B16, V3.B16]
	VUXTL V0.B8, V4.H8
	VUXTL2 V0.B16, V5.H8
	VUXTL V1.B8, V6.H8
	VUXTL2 V1.B16, V7.H8
	VUXTL V2.B8, V8.H8
	VUXTL2 V2.B16, V9.H8

	// Y = 19595R + 38470G + 7471B
	UMULL4S(16, 4, 10)
	UMLAL4S(17, 6, 10)
	UMLAL4S(18, 8, 10)
	UMULL2_4S(16, 4, 11)
	UMLAL2_4S(17, 6, 11)
	UMLAL2_4S(18, 8, 11)
	UMULL4S(16, 5, 12)
	UMLAL4S(17, 7, 12)
	UMLAL4S(18, 9, 12)
	UMULL2_4S(16, 5, 13)
	UMLAL2_4S(17, 7, 13)
	UMLAL2_4S(18, 9, 13)
	VADD V25.S4, V10.S4, V10.S4
	VUSHR $16, V10.S4, V10.S4
	VUMIN V24.S4, V10.S4, V10.S4
	VADD V25.S4, V11.S4, V11.S4
	VUSHR $16, V11.S4, V11.S4
	VUMIN V24.S4, V11.S4, V11.S4
	VADD V25.S4, V12.S4, V12.S4
	VUSHR $16, V12.S4, V12.S4
	VUMIN V24.S4, V12.S4, V12.S4
	VADD V25.S4, V13.S4, V13.S4
	VUSHR $16, V13.S4, V13.S4
	VUMIN V24.S4, V13.S4, V13.S4
	VUZP1 V11.H8, V10.H8, V14.H8
	VUZP1 V13.H8, V12.H8, V15.H8
	VUZP1 V15.B16, V14.B16, V14.B16
	VST1.P [V14.B16], 16(R0)

	// Cb = 32768B - 11056R - 21712G
	UMULL4S(21, 8, 10)
	UMLSL4S(19, 4, 10)
	UMLSL4S(20, 6, 10)
	UMULL2_4S(21, 8, 11)
	UMLSL2_4S(19, 4, 11)
	UMLSL2_4S(20, 6, 11)
	UMULL4S(21, 9, 12)
	UMLSL4S(19, 5, 12)
	UMLSL4S(20, 7, 12)
	UMULL2_4S(21, 9, 13)
	UMLSL2_4S(19, 5, 13)
	UMLSL2_4S(20, 7, 13)
	VADD V26.S4, V10.S4, V10.S4
	VUSHR $16, V10.S4, V10.S4
	VUMIN V24.S4, V10.S4, V10.S4
	VADD V26.S4, V11.S4, V11.S4
	VUSHR $16, V11.S4, V11.S4
	VUMIN V24.S4, V11.S4, V11.S4
	VADD V26.S4, V12.S4, V12.S4
	VUSHR $16, V12.S4, V12.S4
	VUMIN V24.S4, V12.S4, V12.S4
	VADD V26.S4, V13.S4, V13.S4
	VUSHR $16, V13.S4, V13.S4
	VUMIN V24.S4, V13.S4, V13.S4
	VUZP1 V11.H8, V10.H8, V14.H8
	VUZP1 V13.H8, V12.H8, V15.H8
	VUZP1 V15.B16, V14.B16, V14.B16
	VST1.P [V14.B16], 16(R1)

	// Cr = 32768R - 27440G - 5328B
	UMULL4S(21, 4, 10)
	UMLSL4S(22, 6, 10)
	UMLSL4S(23, 8, 10)
	UMULL2_4S(21, 4, 11)
	UMLSL2_4S(22, 6, 11)
	UMLSL2_4S(23, 8, 11)
	UMULL4S(21, 5, 12)
	UMLSL4S(22, 7, 12)
	UMLSL4S(23, 9, 12)
	UMULL2_4S(21, 5, 13)
	UMLSL2_4S(22, 7, 13)
	UMLSL2_4S(23, 9, 13)
	VADD V26.S4, V10.S4, V10.S4
	VUSHR $16, V10.S4, V10.S4
	VUMIN V24.S4, V10.S4, V10.S4
	VADD V26.S4, V11.S4, V11.S4
	VUSHR $16, V11.S4, V11.S4
	VUMIN V24.S4, V11.S4, V11.S4
	VADD V26.S4, V12.S4, V12.S4
	VUSHR $16, V12.S4, V12.S4
	VUMIN V24.S4, V12.S4, V12.S4
	VADD V26.S4, V13.S4, V13.S4
	VUSHR $16, V13.S4, V13.S4
	VUMIN V24.S4, V13.S4, V13.S4
	VUZP1 V11.H8, V10.H8, V14.H8
	VUZP1 V13.H8, V12.H8, V15.H8
	VUZP1 V15.B16, V14.B16, V14.B16
	VST1.P [V14.B16], 16(R2)

	SUB $16, R4, R4
	B loop

done:
	RET
